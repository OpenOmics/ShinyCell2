    '      pmax(h5data$read(args = list(inpGene[g], quote(expr=))), 0)))\n',
    '  }}\n',
    '  targetMat <- readRows(valid)\n',
    '  bgMat     <- readRows(bgGenes)\n',
    '  h5file$close_all()\n',
    '  colMeans(targetMat) - colMeans(bgMat)\n',
    '}}\n',
